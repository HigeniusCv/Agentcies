#!/usr/bin/env python3
"""Emit the canonical SYNTHETIC results section as markdown.

    python3 analysis/results_dump.py > docs/05-RESULTS-TABLES.md

Why this exists: the synthetic-study write-up must quote the numbers the
simulation actually produced, not numbers that sound right. Prose drafted
alongside a simulation drifts from it within one editing pass, and a paper
whose tables disagree with its own code is worse than one with no tables.
This regenerates every figure in the results section straight from
`analyze.py`, so `make results` keeps them honest.

Every table is labelled SYNTHETIC. None of it is evidence about any model.
"""

from __future__ import annotations

import io
import sys
from contextlib import redirect_stdout
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from analyze import (  # noqa: E402
    h0_peak_shift,
    h1_inverted_u,
    h2_structure_effect,
    h3_budget_interaction,
    h4_self_other_gap,
    h5_convergent_validity,
    h6_cross_prediction,
    readout_precision,
    tost_equivalence,
)
from simulate import Params  # noqa: E402

DATA = Path("data")


def fmt(v, nd=3):
    # A key missing from one world's result dict is meaningful, not an error:
    # e.g. H_deflation returns early with no peak, so peak-shift diagnostics
    # simply do not exist there. Render that as an em-dash, never as "None".
    if v is None:
        return "—"
    if isinstance(v, float):
        if v != v:
            return "n/a"
        if 0 < abs(v) < 0.001:
            return "<.001"
        return f"{v:.{nd}f}"
    if isinstance(v, bool):
        return "yes" if v else "no"
    return str(v)


def load(suffix=""):
    return (
        pd.read_csv(DATA / f"synthetic_main{suffix}.csv"),
        pd.read_csv(DATA / f"synthetic_predicted_pref{suffix}.csv"),
        pd.read_csv(DATA / f"synthetic_cross_prediction{suffix}.csv"),
    )


def main() -> None:
    p = Params()
    df, pp, cp = load("")
    dfd, ppd, cpd = load("_deflation")

    buf = io.StringIO()
    with redirect_stdout(buf):
        print("# Synthetic results tables")
        print()
        print("> **Every number below is SIMULATED.** It is generated by")
        print("> `analysis/simulate.py` from stated parameters and analysed by")
        print("> `analysis/analyze.py`. Nothing here is a measurement of any model.")
        print("> Regenerate with `make results`.")
        print()

        # ---- generative parameters ----
        print("## Generative parameters (H_structure)")
        print()
        print("| Parameter | Value | Meaning |")
        print("|---|---:|---|")
        rows = [
            ("intercept", p.intercept, "baseline FlowMoBI index"),
            ("beta_csr_quad", p.beta_csr_quad, "curvature — the inverted-U"),
            ("beta_structure", p.beta_structure, "matched-length structure effect, index pts"),
            ("beta_budget_x_difficulty", p.beta_budget_x_difficulty, "scarcity bites harder when hard"),
            ("beta_length_log2", p.beta_length_log2, "deflationary channel, present in BOTH worlds"),
            ("hint_skill_delta", p.hint_skill_delta, "how far a hint moves effective skill"),
            ("peak_shift_slope", p.peak_shift_slope, "target coupling of peak to skill"),
            ("self_other_gap", p.self_other_gap, "generic-referent minus self"),
            ("blind_self_gap", p.blind_self_gap, "survives identity masking"),
            ("sd_residual", p.sd_residual, "residual SD"),
            ("sd_readout_logprob", p.sd_readout_logprob, "readout noise, logprob providers"),
            ("sd_readout_sampled", p.sd_readout_sampled, "readout noise, sampled providers"),
        ]
        for k, v, why in rows:
            print(f"| `{k}` | {v} | {why} |")
        print()
        print(f"Design: {df.model_spec.nunique()} models × {df.task_id.nunique()} tasks "
              f"× 2 structure levels × 2 hint levels × {df.token_budget.nunique()} budgets "
              f"× {df.replicate.nunique()} replicates = **{len(df):,} trials** "
              f"({df.flow_index.notna().sum():,} usable, "
              f"{100 * df.flow_index.isna().mean():.1f}% degenerate/refused).")
        print()

        # ---- descriptives ----
        print("## Descriptives — SYNTHETIC")
        print()
        d = df.dropna(subset=["flow_index"])
        print("| Cut | n | mean index | SD |")
        print("|---|---:|---:|---:|")
        print(f"| overall | {len(d):,} | {d.flow_index.mean():.1f} | {d.flow_index.std():.1f} |")
        for lvl, g in d.groupby("level"):
            print(f"| structure = {lvl} | {len(g):,} | {g.flow_index.mean():.1f} | {g.flow_index.std():.1f} |")
        for b, g in d.groupby("token_budget"):
            print(f"| budget = {b} | {len(g):,} | {g.flow_index.mean():.1f} | {g.flow_index.std():.1f} |")
        for h, g in d.groupby("hint"):
            print(f"| hint = {h} | {len(g):,} | {g.flow_index.mean():.1f} | {g.flow_index.std():.1f} |")
        print()

        # ---- hypothesis tests, both worlds ----
        tests = [
            ("H0 (primary) — peak shift", h0_peak_shift, (df,), (dfd,)),
            ("H1 — inverted-U", h1_inverted_u, (df,), (dfd,)),
            ("H2 — matched-length structure", h2_structure_effect, (df,), (dfd,)),
            ("H3 — budget × difficulty", h3_budget_interaction, (df,), (dfd,)),
            ("H5 — convergent validity", h5_convergent_validity, (df,), (dfd,)),
            ("H6 — cross-prediction", h6_cross_prediction, (cp,), (cpd,)),
        ]
        for title, fn, args_s, args_d in tests:
            rs, rd = fn(*args_s), fn(*args_d)
            print(f"## {title} — SYNTHETIC")
            print()
            print("| Quantity | H_structure | H_deflation |")
            print("|---|---:|---:|")
            for k in rs:
                if k == "test":
                    continue
                print(f"| `{k}` | {fmt(rs.get(k))} | {fmt(rd.get(k))} |")
            print()

        # ---- H4 ----
        r4s, r4d = h4_self_other_gap(pp), h4_self_other_gap(ppd)
        print("## H4 — self–other gap — SYNTHETIC")
        print()
        print("| Contrast | H_structure gap | dz | p (clustered) | H_deflation gap | p (clustered) |")
        print("|---|---:|---:|---:|---:|---:|")
        for sub, label in [
            ("self_vs_generic", "self vs generic model"),
            ("self_vs_human", "self vs human"),
            ("self_vs_blind", "self vs **blind-self**"),
        ]:
            a, b = r4s[sub], r4d[sub]
            print(f"| {label} | {a['mean_gap']:+.2f} | {a['cohens_dz']:+.2f} | "
                  f"{fmt(a['p_clustered'])} | {b['mean_gap']:+.2f} | {fmt(b['p_clustered'])} |")
        print()
        print(f"Blind/generic ratio: **{r4s['blind_over_generic_ratio']:.3f}** under H_structure "
              f"versus **{r4d['blind_over_generic_ratio']:.3f}** under H_deflation. That ratio is the "
              "whole test — a gap that vanishes when the referent's identity is masked was a "
              "register effect, not self-knowledge.")
        print()

        # ---- readout ----
        rp = readout_precision(df)
        print("## Readout precision — SYNTHETIC")
        print()
        print("| Quantity | Value |")
        print("|---|---:|")
        for k, v in rp.items():
            if k != "test":
                print(f"| `{k}` | {fmt(v)} |")
        print()

        # ---- equivalence ----
        print("## Equivalence testing — so a null is informative")
        print()
        gaps = (ppd["flow_blind_self"] - ppd["flow_self"]).to_numpy()
        t = tost_equivalence(gaps, bound=3.0)
        print("Applied to the blind-self gap under H_deflation, where the true effect is zero:")
        print()
        print("| Quantity | Value |")
        print("|---|---:|")
        for k, v in t.items():
            print(f"| `{k}` | {fmt(v)} |")
        print()
        print("A non-significant test is not evidence of absence; TOST against a "
              "smallest-effect-of-interest is. The ±3 index-point bound is one tenth of "
              "the human scale's usable range — below that, no product researcher would act "
              "on the difference.")
        print()

        print("---")
        print()
        print("*Regenerate: `make results`. Source: `analysis/simulate.py`, "
              "`analysis/analyze.py`, `analysis/results_dump.py`.*")

    sys.stdout.write(buf.getvalue())


if __name__ == "__main__":
    main()
